#!/usr/bin/env node
/**
 * Extract PublicLiquidityPool creation bytecode for in-browser pool deploys.
 * Run from `frontend/`: npm run copy-pool-bytecode
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const artifactPath = path.resolve(
  __dirname,
  '../../Aegis-contracts/artifacts/contracts/liquidity/PublicLiquidityPool.sol/PublicLiquidityPool.json',
)
const outPath = path.resolve(__dirname, '../src/deploy/publicLiquidityPoolBytecode.ts')

if (!fs.existsSync(artifactPath)) {
  console.error(`Missing artifact: ${artifactPath}\nCompile Aegis-contracts first.`)
  process.exit(1)
}

const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'))
const bytecode = artifact.bytecode
if (!bytecode || bytecode === '0x') {
  console.error('Artifact has no deployment bytecode')
  process.exit(1)
}

const content = `/** Auto-generated by scripts/copy-pool-bytecode.mjs — do not edit. */
export const PUBLIC_LIQUIDITY_POOL_BYTECODE = ${JSON.stringify(bytecode)} as const
`

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, content, 'utf8')
console.log(`Wrote ${path.relative(path.resolve(__dirname, '..'), outPath)} (${bytecode.length} chars)`)
